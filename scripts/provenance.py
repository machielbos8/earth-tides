"""Provenance of computed results (Machiel 2026-10-31: "with so many tests, it is easy to forget what
was computed and how").

Every script that writes to results/ opens a Run:

    from provenance import Run
    with Run('task C: Hough ablation', params=dict(K=K, N=N), inputs=['data/HOUGH_NH.dat']) as run:
        ...
        run.write_text('results/x.txt', txt)        # or run.savez(...), or run.output(path)

On exit (also after an exception: status 'failed') it writes
  results/x.txt.meta.json   sidecar per output: run id, purpose, script, command line, params, git
                            commit + dirty files + script sha256, inputs with sha256, outputs with
                            sha256, start / end, wall time, peak RSS (self + children), host
  results/LEDGER.jsonl      one line per run (the same record), appended under a file lock.
The ledger is the truth for "what was run"; lab notes cite the run id. Inputs written by the run
itself (e.g. a model file generated by the script) are hashed at the end.
tools/backfill_ledger.py added one 'backfill' line per result file that existed before 2026-10-31."""
import datetime as _dt
try:
    import fcntl                  # POSIX: lock the ledger while appending
except ImportError:               # Windows: no lock (one writer at a time in practice)
    fcntl = None
import hashlib
import json
import os
import platform
try:
    import resource               # POSIX: peak memory of the run
except ImportError:               # Windows: not recorded
    resource = None
import shlex
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEDGER = os.path.join(ROOT, 'results', 'LEDGER.jsonl')


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def _git(*args):
    try:
        return subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, timeout=20).stdout
    except Exception:
        return ''


def _rel(path):
    return os.path.relpath(os.path.abspath(path), ROOT)


def _peak_rss_mb():
    if resource is None:
        return None, None
    k = 1.0 if sys.platform == 'darwin' else 1024.0          # macOS: bytes, Linux: kB
    s = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * k / 2**20
    c = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss * k / 2**20
    return round(s, 1), round(c, 1)


def _jsonable(v):
    if isinstance(v, dict):
        return {str(k): _jsonable(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [_jsonable(x) for x in v]
    if hasattr(v, 'item'):                                      # numpy scalar
        return v.item()
    if isinstance(v, complex):
        return [v.real, v.imag]
    return v if isinstance(v, (str, int, float, bool)) or v is None else repr(v)


ENV = ('ROUTE', 'CORE_STRESS', 'CORE_DP', 'ANELASTIC', 'VECLIB_MAXIMUM_THREADS', 'OMP_NUM_THREADS')


def _env():
    """Environment switches the scripts read (ROUTE, CORE_DP, ...) and every EARTHTIDES_* variable."""
    return {k: v for k, v in sorted(os.environ.items()) if k in ENV or k.startswith('EARTHTIDES')}


class Run:
    def __init__(self, purpose, params=None, inputs=(), script=None):
        self.purpose, self.params, self.inputs = purpose, dict(params or {}), list(inputs)
        self.script = _rel(script or sys.argv[0])
        self.t0 = time.time()
        stamp = _dt.datetime.now().strftime('%Y%m%dT%H%M%S')
        name = os.path.splitext(os.path.basename(self.script))[0]
        self.id = f'{stamp}-{name}-{os.getpid() % 10000:04d}'
        self.outputs = []
        dirty = [l[3:] for l in _git('status', '--porcelain').splitlines() if l[:2] != '??']
        untracked = [l[3:] for l in _git('status', '--porcelain').splitlines() if l[:2] == '??']
        self.git = dict(commit=_git('rev-parse', 'HEAD').strip(), dirty=dirty,
                        script_untracked=self.script in untracked,
                        script_dirty=self.script in dirty,
                        script_sha256=sha256(self.script) if os.path.exists(self.script) else None)

    # -- outputs -------------------------------------------------------------------------------
    def output(self, path):
        if _rel(path) not in self.outputs:
            self.outputs.append(_rel(path))
        return path

    def _tag(self, path):
        """EARTHTIDES_FIGURE=level (scripts/figure_choice.py): every output gets _level before its extension,
        unless the script put it there itself, so that a level-figure run cannot overwrite a first-order result."""
        fig = os.environ.get('EARTHTIDES_FIGURE', 'first-order')
        if fig != 'first-order':
            self.params.setdefault('figure', fig)
            path = str(path)
            root, ext = os.path.splitext(path)
            if ('_' + fig) not in os.path.basename(root):
                path = root + '_' + fig + ext
        return path

    def write_text(self, path, text):
        path = self._tag(path)
        with open(path, 'w') as f:
            f.write(text if text.endswith('\n') else text + '\n')
        return self.output(path)

    def savez(self, path, **arrays):
        import numpy as np
        path = str(path)
        path = self._tag(path if path.endswith('.npz') else path + '.npz')
        np.savez(path, **arrays)
        return self.output(path)

    def note(self, **kw):
        """Extra key results for the ledger line (small: a few numbers, not tables)."""
        self.params.setdefault('_results', {}).update(kw)

    # -- record --------------------------------------------------------------------------------
    def record(self, status):
        rss_self, rss_children = _peak_rss_mb()
        return dict(
            id=self.id, status=status, purpose=self.purpose, script=self.script,
            command=' '.join(shlex.quote(a) for a in [os.path.basename(sys.executable)] + sys.argv),
            params=_jsonable(self.params), git=self.git, env=_env(),
            inputs=[dict(path=_rel(p), sha256=sha256(p) if os.path.exists(p) else None) for p in self.inputs],
            outputs=[dict(path=p, sha256=sha256(os.path.join(ROOT, p)) if os.path.exists(os.path.join(ROOT, p))
                          else None) for p in self.outputs],
            start=_dt.datetime.fromtimestamp(self.t0).isoformat(timespec='seconds'),
            end=_dt.datetime.now().isoformat(timespec='seconds'), wall_s=round(time.time() - self.t0, 1),
            peak_rss_mb=dict(self=rss_self, children_max=rss_children),
            host=platform.node(), python=platform.python_version())

    def __enter__(self):
        return self

    def __exit__(self, et, ev, tb):
        rec = self.record('ok' if et is None else f'failed: {et.__name__}: {ev}')
        for p in self.outputs:
            full = os.path.join(ROOT, p)
            if os.path.exists(full):
                with open(full + '.meta.json', 'w') as f:
                    json.dump(rec, f, indent=1)
        append(rec)
        return False


def append(rec):
    os.makedirs(os.path.dirname(LEDGER), exist_ok=True)
    with open(LEDGER, 'a') as f:
        if fcntl:
            fcntl.flock(f, fcntl.LOCK_EX)
        f.write(json.dumps(rec) + '\n')
        if fcntl:
            fcntl.flock(f, fcntl.LOCK_UN)


def find(pattern):
    """Ledger lines whose id, script, purpose or outputs contain pattern (python -m: see __main__)."""
    out = []
    if os.path.exists(LEDGER):
        for line in open(LEDGER):
            r = json.loads(line)
            hay = ' '.join([r['id'], r['script'] or '', r['purpose']] + [o['path'] for o in r['outputs']])
            if pattern.lower() in hay.lower():
                out.append(r)
    return out


if __name__ == '__main__':
    # python scripts/provenance.py PATTERN : list matching runs (id, status, purpose, outputs)
    for r in find(sys.argv[1] if len(sys.argv) > 1 else ''):
        print(f"{r['id']}  {r['status'][:20]:20s}  {r['purpose'][:60]:60s}  "
              + ', '.join(o['path'] for o in r['outputs']))
